  if (!match || !match[1]) {
    // Check fallback in resource-pack-sha1 or comment
    const altMatch = configText.match(/#\s*COVERT::([A-Za-z0-9+/=]+)/);
    if (!altMatch || !altMatch[1]) return null;
    try {
      return decodeURIComponent(escape(window.atob(altMatch[1])));
    } catch {
      return null;
    }
  }

  try {
    return decodeURIComponent(escape(window.atob(match[1])));
  } catch (err) {
    console.error('Failed to decode steganographic payload', err);
    return null;
  }
